#!/usr/bin/env bash
# Rebuild every portfolio exercise from scratch and save the raw output as evidence.
#
#   ./run_all.sh                     Portfolios 1-4 (PostgreSQL + MongoDB)
#   ./run_all.sh --with-replica-set  also run the Portfolio 5 replica-set demonstration
#
# Requirements: psql, mongosh, python3 with psycopg2 (pip install -r requirements.txt).
# Portfolio 5 also needs the mongod binary on PATH.
# Connection settings come from the usual PG* variables and MONGO_URI, for example the
# services in docker-compose.yml:  PGHOST=localhost PGUSER=postgres PGPASSWORD=postgres
#
# WARNING: the exercise database (EXERCISE_DB, default mit_portfolio) and the MongoDB
# database portfolio_nosql are dropped and recreated on every run.
set -euo pipefail
cd "$(dirname "$0")"

EXERCISE_DB="${EXERCISE_DB:-mit_portfolio}"
MONGO_URI="${MONGO_URI:-mongodb://localhost:27017}"
export PGTZ=UTC

P1=portfolio-1-database-design
P2=portfolio-2-query-optimisation
P3=portfolio-3-transactions-concurrency
P4=portfolio-4-nosql
P5=portfolio-5-distributed-cloud
ID=Ukaegbu_Goodnews_301923986

header() {  # header <title>
  echo "# $1"
  echo "# Generated by run_all.sh on $(date -u '+%Y-%m-%d %H:%M:%S UTC')"
}
pg_version() { psql -X -d postgres -At -c "SHOW server_version"; }
run_sql() {  # run_sql <file> [extra psql options...]  (stops on the first error)
  local file="$1"; shift
  psql -X -d "$EXERCISE_DB" -v ON_ERROR_STOP=1 -a "$@" -f "$file" 2>&1
}

echo "== Fresh PostgreSQL database: $EXERCISE_DB"
psql -X -d postgres -q -c "DROP DATABASE IF EXISTS $EXERCISE_DB" -c "CREATE DATABASE $EXERCISE_DB"

# ---------------------------------------------------------------- Portfolio 1
echo "== Portfolio 1"
mkdir -p "$P1/evidence"
{
  header "Portfolio 1 - schema, sample data and verification (PostgreSQL $(pg_version))"
  run_sql "$P1/${ID}_P1_Schema.sql"
  run_sql "$P1/${ID}_P1_SampleData.sql"
} > "$P1/evidence/${ID}_P1_SchemaAndData.txt"
{
  header "Portfolio 1 - deliberately invalid inserts, each run on its own (PostgreSQL $(pg_version))"
  # ON_ERROR_STOP=0: every statement runs in its own autocommit transaction and is expected to fail.
  psql -X -d "$EXERCISE_DB" -v ON_ERROR_STOP=0 -v VERBOSITY=verbose -a \
       -f "$P1/${ID}_P1_ConstraintTests.sql" 2>&1 || true
} > "$P1/evidence/${ID}_P1_ConstraintTests.txt"
{
  header "Portfolio 1 - catalog checks and normalisation check (PostgreSQL $(pg_version))"
  run_sql "$P1/${ID}_P1_Verify.sql"
} > "$P1/evidence/${ID}_P1_Verify.txt"
expected=$(grep -c '^-- [0-9]*\. .*Expected:' "$P1/${ID}_P1_ConstraintTests.sql")
rejected=$(grep -c '^psql:.*ERROR:  23[0-9]\{3\}:' "$P1/evidence/${ID}_P1_ConstraintTests.txt" || true)
echo "   constraint tests: $rejected of $expected rejected"

# ---------------------------------------------------------------- Portfolio 2
echo "== Portfolio 2"
mkdir -p "$P2/evidence"
{
  header "Portfolio 2 - case queries and execution plans (PostgreSQL $(pg_version))"
  run_sql "$P2/${ID}_P2_Queries.sql"
} > "$P2/evidence/${ID}_P2_Queries.txt"
{
  header "Portfolio 2 - index benchmark on 50,000 rows (PostgreSQL $(pg_version))"
  run_sql "$P2/${ID}_P2_Optimisation.sql"
} > "$P2/evidence/${ID}_P2_Optimisation.txt"

# ---------------------------------------------------------------- Portfolio 3
echo "== Portfolio 3"
mkdir -p "$P3/evidence"
{
  header "Portfolio 3 - COMMIT, ROLLBACK and constraint failure (PostgreSQL $(pg_version))"
  run_sql "$P3/${ID}_P3_Transactions.sql"
} > "$P3/evidence/${ID}_P3_Transactions.txt"
python3 tools/two_session_driver.py --dbname "$EXERCISE_DB" \
  --title "Portfolio 3 - lost update on a counter vs SELECT FOR UPDATE" \
  "$P3/${ID}_P3_SessionA.sql" "$P3/${ID}_P3_SessionB.sql" \
  > "$P3/evidence/${ID}_P3_CounterSessions.txt"
python3 tools/two_session_driver.py --dbname "$EXERCISE_DB" \
  --title "Portfolio 3 - concurrent payments from one account (READ COMMITTED, FOR UPDATE, REPEATABLE READ)" \
  "$P3/${ID}_P3_Payments_SessionA.sql" "$P3/${ID}_P3_Payments_SessionB.sql" \
  > "$P3/evidence/${ID}_P3_PaymentSessions.txt"
{
  header "Portfolio 3 - cleanup (PostgreSQL $(pg_version))"
  run_sql "$P3/${ID}_P3_Cleanup.sql"
} > "$P3/evidence/${ID}_P3_Cleanup.txt"

# ---------------------------------------------------------------- Portfolio 4
echo "== Portfolio 4"
mkdir -p "$P4/evidence"
mongosh "$MONGO_URI" --quiet --eval 'db.getSiblingDB("portfolio_nosql").dropDatabase()' > /dev/null
{
  header "Portfolio 4 - MongoDB payment_event model, queries, explain and validation (MongoDB $(mongosh "$MONGO_URI" --quiet --eval 'db.version()'))"
  mongosh "$MONGO_URI" --quiet --file "$P4/${ID}_P4_MongoDB.js" 2>&1
} > "$P4/evidence/${ID}_P4_MongoDB.txt"

# ---------------------------------------------------------------- Portfolio 5
if [[ "${1:-}" == "--with-replica-set" ]]; then
  echo "== Portfolio 5"
  mkdir -p "$P5/evidence"
  bash "$P5/${ID}_P5_ReplicaSetDemo.sh" > "$P5/evidence/${ID}_P5_ReplicaSetDemo.txt" 2>&1
fi

echo "Done. Raw output is in each portfolio's evidence/ folder."
